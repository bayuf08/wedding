import { expect, test } from '@playwright/test'

for (const width of [320, 390, 1680]) {
  test(`wedding forms preserve validation, keyboard and preview flows at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 939 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/invite/demo?to=Guest+Name')
    await page.getByRole('button', { name: "Let's Open" }).click()
    await expect(page.locator('.opening-cover')).toHaveCount(0)
    const rsvp = page.locator('.rsvp-form')
    await expect(page.locator('#rsvp-name')).toHaveValue('Guest Name')
    await expect(page.locator('#rsvp-name')).toHaveAttribute('readonly')
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await expect(page.locator('#rsvp-attendance')).toBeFocused()
    await expect(page.locator('#rsvp-attendance-error')).toBeVisible()
    await page.keyboard.press('Space')
    await expect(page.getByRole('radio', { name: 'Attending', exact: true })).toBeChecked()
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await expect(page.locator('#rsvp-eventId')).toBeFocused()
    await page.getByRole('radio', { name: 'Akad Nikah', exact: true }).check()
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await expect(page.locator('#rsvp-attendanceCount')).toBeFocused()
    await page.getByRole('radio', { name: '2 guests', exact: true }).check()
    await page.locator('#rsvp-note').fill('a'.repeat(501))
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await expect(page.locator('#rsvp-note')).toBeFocused()
    await expect(page.locator('#rsvp-note-error')).toBeVisible()
    await page.locator('#rsvp-note').fill('Local preview test only.')
    await page.clock.install({ time: new Date('2026-10-24T12:00:00Z') })
    await page.clock.pauseAt(new Date('2026-10-24T12:00:01Z'))
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await expect(rsvp).toHaveAttribute('aria-busy', 'true')
    await expect(rsvp.getByRole('button', { name: 'Saving…' })).toBeDisabled()
    await page.clock.runFor(300)
    await expect(rsvp.getByRole('status')).toContainText('saved for this preview')
    await expect(rsvp).toHaveAttribute('aria-busy', 'false')
    await page.getByRole('radio', { name: 'Attending', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('radio', { name: 'Not Attending', exact: true })).toBeChecked()
    await expect(page.locator('#rsvp-eventId')).toHaveCount(0)
    await rsvp.getByRole('button', { name: 'Send Confirmation' }).click()
    await page.clock.runFor(300)
    await expect(rsvp.getByRole('status')).toContainText('saved for this preview')
    await page.locator('#rsvp-note').screenshot({ path: `/tmp/wedding-form-message-${width}.png` })
    await page.locator('.rsvp-column').screenshot({ path: `/tmp/wedding-form-rsvp-${width}.png` })
    expect(await rsvp.evaluate(form => [...form.querySelectorAll('input:not([type=radio]),textarea,.form-choice,button')].every(el => el.getBoundingClientRect().right <= innerWidth && el.getBoundingClientRect().left >= 0))).toBe(true)

    await page.getByRole('button', { name: 'Confirm Gift', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Wedding gift' })
    const form = dialog.locator('form')
    const send = form.getByRole('button', { name: 'Send Gift Confirmation' })
    await send.click()
    await expect(dialog.locator('.field-error')).toHaveCount(3)
    await expect(page.locator('#gift-name')).toBeFocused()
    await expect(page.locator('#gift-name')).toHaveAttribute('aria-describedby', 'gift-name-error')
    await page.locator('#gift-name').fill('Local Test')
    await send.click()
    await expect(page.locator('#gift-bank')).toBeFocused()
    await page.locator('#gift-bank').selectOption('preview-a')
    await page.locator('#gift-amount').fill('-1')
    await send.click()
    await expect(page.locator('#gift-amount')).toBeFocused()
    await expect(page.locator('#gift-amount-error')).toBeVisible()
    await page.locator('#gift-amount').fill('1')
    await page.locator('#gift-note').fill('Local preview test only.')
    await send.click()
    await expect(form.getByRole('status')).toContainText('Preview confirmation recorded')
    await dialog.locator('.gift-form-panel').screenshot({ path: `/tmp/wedding-form-gift-${width}.png` })
    expect(await form.evaluate(el => el.scrollWidth <= el.clientWidth && el.getBoundingClientRect().right <= innerWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Confirm Gift', exact: true })).toBeFocused()
  })
}
