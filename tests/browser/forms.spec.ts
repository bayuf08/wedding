import { expect, test } from '@playwright/test'

for (const width of [320, 390, 768, 1680]) {
  test(`wedding forms preserve validation, keyboard and preview flows at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 939 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/invite/demo?to=Guest+Name')
    await page.getByRole('button', { name: "Let's Open" }).click()
    await expect(page.locator('.opening-cover')).toHaveCount(0)
    const rsvp = page.locator('.rsvp-form')
    const count = page.locator('#rsvp-attendanceCount')
    await expect(page.locator('#rsvp-name')).toHaveValue('Guest Name')
    await expect(page.locator('#rsvp-name')).toHaveAttribute('readonly')
    await page.locator('#rsvp-name').focus()
    await expect(page.locator('#rsvp-name')).toHaveCSS('outline-style', 'none')
    expect(await page.locator('#rsvp-name').evaluate(el => getComputedStyle(el.nextElementSibling!, '::after').transform)).not.toBe('matrix(0, 0, 0, 1, 0, 0)')
    await expect(page.getByRole('radio', { name: 'Attending', exact: true })).toBeChecked()
    await expect(page.locator('#rsvp-eventId')).toHaveCount(0)
    await expect(count).toBeVisible()
    await expect(count).not.toBeChecked()
    await expect(page.locator('input[name=attendance-count]')).toHaveCount(2)
    await rsvp.getByRole('button', { name: 'Review RSVP' }).click()
    await expect(count).toBeFocused()
    await page.locator('#rsvp-attendanceCount-1').check()
    await page.locator('#rsvp-note').fill('a'.repeat(501))
    await rsvp.getByRole('button', { name: 'Review RSVP' }).click()
    await expect(page.locator('#rsvp-note')).toBeFocused()
    await expect(page.locator('#rsvp-note-error')).toBeVisible()
    await page.locator('#rsvp-note').fill('Local preview test only.')
    await page.clock.install({ time: new Date('2026-10-24T12:00:00Z') })
    await page.clock.pauseAt(new Date('2026-10-24T12:00:01Z'))
    await rsvp.getByRole('button', { name: 'Review RSVP' }).click()
    await expect(rsvp).toHaveAttribute('aria-busy', 'true')
    await expect(rsvp.getByRole('button', { name: 'Checking…' })).toBeDisabled()
    await page.clock.runFor(300)
    await expect(rsvp.getByRole('status')).toContainText('Nothing has been sent or saved')
    await page.getByRole('radio', { name: 'Attending', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('radio', { name: 'Not Attending', exact: true })).toBeChecked()
    await expect(count).toHaveCount(0)
    await expect(page.locator('#rsvp-attendanceCount-error')).toHaveCount(0)
    await rsvp.getByRole('button', { name: 'Review RSVP' }).click()
    await page.clock.runFor(300)
    await expect(rsvp.getByRole('status')).toContainText('Nothing has been sent or saved')
    await page.getByRole('radio', { name: 'Attending', exact: true }).check()
    await expect(page.locator('#rsvp-attendanceCount-1')).toBeChecked()
    await count.check()
    await page.locator('.rsvp-column').screenshot({ path: `/tmp/wedding-shared-rsvp-${width}.png` })
    expect(await rsvp.evaluate(form => [...form.querySelectorAll('input:not([type=radio]),textarea,.form-choice,button')].every(el => el.getBoundingClientRect().right <= innerWidth && el.getBoundingClientRect().left >= 0))).toBe(true)
    await page.getByRole('button', { name: 'Confirm Gift', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Wedding gift' })
    const form = dialog.locator('form')
    const send = form.getByRole('button', { name: 'Review Gift Confirmation' })
    await send.click()
    await expect(dialog.locator('.field-error')).toHaveCount(3)
    await expect(page.locator('#gift-name')).toBeFocused()
    await expect(page.locator('#gift-name')).toHaveAttribute('aria-describedby', 'gift-name-error')
    await page.locator('#gift-name').fill('Local Test')
    await send.click()
    await expect(page.locator('#gift-bank')).toBeFocused()
    await page.locator('#gift-bank').check()
    await page.locator('#gift-amount').fill('-1')
    await send.click()
    await expect(page.locator('#gift-amount')).toBeFocused()
    await expect(page.locator('#gift-amount-error')).toBeVisible()
    await page.locator('#gift-amount').fill('1')
    await page.locator('#gift-note').fill('Local preview test only.')
    await send.click()
    await expect(form.getByRole('status')).toContainText('Gift details checked on this page')
    await dialog.locator('.gift-form-panel').screenshot({ path: `/tmp/wedding-shared-gift-${width}.png` })
    expect(await form.evaluate(el => el.scrollWidth <= el.clientWidth && el.getBoundingClientRect().right <= innerWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Confirm Gift', exact: true })).toBeFocused()
  })
}

test('shared form focus, hover, press, companion and reduced-motion states', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/invite/demo?to=Guest+Name')
  await page.getByRole('button', { name: "Let's Open" }).click()
  await expect(page.locator('.opening-cover')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const note = page.locator('#rsvp-note')
  const field = note.locator('..')
  await note.focus()
  await expect(page.locator('.rsvp-visual-column .form-companion')).toHaveAttribute('data-context', 'Wishes/Message')
  await expect.poll(() => field.locator('.field-rule').evaluate(el => getComputedStyle(el, '::after').transform)).toBe('matrix(1, 0, 0, 2, 0, 0)')
  await note.fill('Local shared component test.')
  await page.locator('#rsvp-name').focus()
  await expect(field).toHaveClass(/is-filled/)
  await expect(note).toHaveValue('Local shared component test.')
  await field.hover()
  const label = field.locator('.invitation-label')
  await expect.poll(() => label.evaluate(el => getComputedStyle(el).color)).toBe('rgb(239, 239, 237)')
  const choice = page.getByRole('radio', { name: 'Attending', exact: true })
  await choice.locator('..').hover()
  await choice.check()
  await expect(choice).toBeChecked()
  const action = page.locator('.rsvp-form .form-submit')
  await action.hover()
  await expect.poll(() => action.locator('.action-corner--tl').evaluate(el => getComputedStyle(el).transform)).toBe('matrix(1, 0, 0, 1, -2, -2)')
  await page.mouse.down()
  await expect.poll(() => action.locator('.action-label').evaluate(el => getComputedStyle(el).transform)).toBe('matrix(1, 0, 0, 1, 0, 1)')
  await page.mouse.move(5, 5)
  await page.mouse.up()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await note.focus()
  expect(await field.locator('.field-rule').evaluate(el => getComputedStyle(el, '::after').transitionDuration)).toBe('0s')
  expect(await action.locator('.action-corner--tl').evaluate(el => getComputedStyle(el).transitionDuration)).toBe('0s')
  await page.getByRole('button', { name: 'Confirm Gift', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Wedding gift' })
  await page.locator('#gift-name').fill('Local Test')
  await page.locator('#gift-bank').check()
  await page.locator('#gift-amount').fill('1')
  await page.locator('#gift-note').fill('Private local note')
  await expect(dialog.locator('.form-companion')).toHaveAttribute('data-context', 'Note')
  await expect(dialog.locator('.form-companion')).not.toContainText('Private local note')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Confirm Gift', exact: true }).click()
  await expect(page.locator('#gift-name')).toHaveValue('Local Test')
  await expect(page.locator('#gift-amount')).toHaveValue('1')
  await dialog.locator('.gift-form-panel').screenshot({ path: '/tmp/wedding-shared-gift-desktop.png' })
  await page.keyboard.press('Escape')
  await page.locator('.rsvp-layout').screenshot({ path: '/tmp/wedding-shared-rsvp-desktop.png' })
})
